"""Collects the UI texts into ZenshiroDev/resources/lang/zenlink.pot and updates every
<code>.po file next to it: new texts are added untranslated, texts no longer in the code
are dropped, translations are kept.

Texts are the English strings in I18n.t("...") / I18n.f("...", x) (Slint) and
i18n::tr("...") / trf!("...") (Rust). Texts built at run time (backend messages,
labels picked in code) are kept from the existing id.po: add them by hand there.

    python ZenshiroDev/tooling/dev/extract_texts.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LANG = ROOT / 'ZenshiroDev/resources/lang'
LIT = r'"((?:[^"\\]|\\.)*)"'
CALLS = re.compile(r'(?:I18n\.[tf]|i18n::tr|trf!)\(\s*' + LIT)


def unescape(body):
    out, i = [], 0
    while i < len(body):
        c = body[i]
        if c == '\\' and i + 1 < len(body):
            n = body[i + 1]
            out.append({'n': '\n', 't': '\t'}.get(n, n))
            i += 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def quote(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t') + '"'


def read_po(path):
    """[(msgid, msgstr, comments)] in file order, header first."""
    entries, cur, field, comments = [], None, None, []
    for line in path.read_text(encoding='utf-8').splitlines():
        line = line.strip()
        if line.startswith('#'):
            comments.append(line)
        elif line.startswith('msgid '):
            if cur:
                entries.append(cur)
            cur, field = [unescape(line[7:-1]), '', comments], 0
            comments = []
        elif line.startswith('msgstr '):
            cur[1], field = unescape(line[8:-1]), 1
        elif line.startswith('"') and cur:
            cur[field] += unescape(line[1:-1])
    if cur:
        entries.append(cur)
    return entries


def write_po(path, header, entries):
    lines = header
    for msgid, msgstr, comments in entries:
        lines += [''] + comments + [f'msgid {quote(msgid)}', f'msgstr {quote(msgstr)}']
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')


def main():
    found = {}
    files = sorted((ROOT / 'apps/desktop/ui').glob('*.slint')) + [f for f in sorted((ROOT / 'apps/desktop/src').glob('*.rs')) if f.name != 'i18n.rs']
    for f in files:
        text = f.read_text(encoding='utf-8')
        for m in CALLS.finditer(text):
            body = m.group(1)
            if f.suffix == '.rs':
                body = re.sub(r'\\\r?\n\s*', '', body)  # Rust line continuations
            msgid = unescape(body)
            line = text.count('\n', 0, m.start()) + 1
            found.setdefault(msgid, f'#: {f.relative_to(ROOT).as_posix()}:{line}')
    pot_header = ['# ZenLink UI texts. Generated by ZenshiroDev/tooling/dev/extract_texts.py.',
                  'msgid ""', 'msgstr ""', '"Content-Type: text/plain; charset=UTF-8\\n"']
    write_po(LANG / 'zenlink.pot', pot_header, [(k, '', [v]) for k, v in found.items()])
    for po in sorted(LANG.glob('*.po')):
        old = read_po(po)
        header_entry = next((e for e in old if e[0] == ''), None)
        known = {e[0]: e[1] for e in old if e[0]}
        # Hand-added texts (run-time ones) stay; they carry no "#:" source line.
        manual = [(k, v, ['#. added by hand']) for e in old if e[0]
                  for k, v in [(e[0], e[1])] if k not in found and '#. added by hand' in e[2]]
        entries = [(k, known.get(k, ''), [src]) for k, src in found.items()] + manual
        header = (header_entry[2] if header_entry else []) + ['msgid ""', 'msgstr ""'] + \
            [quote(l + '\n') for l in (header_entry[1] if header_entry else '').splitlines()]
        write_po(po, header, entries)
        missing = sum(1 for e in entries if not e[1])
        print(f'{po.name}: {len(entries)} texts, {missing} untranslated')
    print(f'zenlink.pot: {len(found)} texts')


if __name__ == '__main__':
    sys.exit(main())
